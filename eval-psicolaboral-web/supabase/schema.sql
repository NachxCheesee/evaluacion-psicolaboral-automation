-- 1. Tabla de cuentas (login simulado: contraseña en claro, solo demo.
--    En la Opción B esto se reemplaza por Supabase Auth + profiles).
create table if not exists public.cuentas (
  id bigint generated by default as identity primary key,
  correo text not null unique,
  password text not null,
  nombre text not null,
  rol text not null check (rol in ('ADMIN', 'ANALISTA', 'EVALUADOR')),
  titulo_rol text,
  fecha_alta date default current_date
);

-- 2. Tabla de solicitudes (la evaluación viaja anidada como jsonb,
--    igual que el objeto "evaluacion" de mockData.js)
create table if not exists public.solicitudes (
  id bigint generated by default as identity primary key,
  rut text,
  candidato text not null,
  correo text,
  telefono text,
  direccion text,
  cargo text not null,
  familia_cargo text,
  fecha_solicitud date not null default current_date,
  solicitado_por text,
  responsable text,
  cv_adjunto text,
  estado text not null default 'Pendiente'
    check (estado in ('Pendiente', 'En proceso', 'Finalizada')),
  observaciones text,
  evaluacion jsonb not null default jsonb_build_object(
    'fechaEntrevista', '',
    'resultado', '',
    'observacionesEvaluador', '',
    'archivoTranscripcion', '',
    'archivoInformeFinal', ''
  )
);

-- 3. Índices de apoyo para los filtros del listado
create index if not exists idx_solicitudes_estado on public.solicitudes (estado);
create index if not exists idx_solicitudes_fecha on public.solicitudes (fecha_solicitud desc);
create index if not exists idx_solicitudes_candidato on public.solicitudes (candidato);

-- 4. Row Level Security
alter table public.cuentas enable row level security;
alter table public.solicitudes enable row level security;

-- Opción A (sin Auth real): permiso total para la clave anon.
-- En la Opción B se reemplazan por políticas por rol usando get_my_role().
drop policy if exists "anon CRUD cuentas" on public.cuentas;
create policy "anon CRUD cuentas"
  on public.cuentas for all to anon
  using (true) with check (true);

drop policy if exists "anon CRUD solicitudes" on public.solicitudes;
create policy "anon CRUD solicitudes"
  on public.solicitudes for all to anon
  using (true) with check (true);
