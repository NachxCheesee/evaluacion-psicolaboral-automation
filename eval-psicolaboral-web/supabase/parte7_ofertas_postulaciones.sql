-- ============================================================
-- Parte 7 - Ofertas, postulantes y postulaciones (AquaChile)
-- ------------------------------------------------------------
-- Ejecutar DESPUES de parte5_ia_compatibilidad.sql.
-- Modela el portal publico de ofertas y la postulacion publica
-- que guarda el CV en Google Drive y crea la solicitud de evaluacion.
-- Es idempotente.
-- ============================================================

begin;

-- 1. Compatibilidad con el backend de CV ------------------------

alter table public.solicitudes
  add column if not exists cv_drive_file_id text;

-- 2. Ofertas ----------------------------------------------------

create table if not exists public.ofertas (
  id bigint generated by default as identity primary key,
  cargo text not null,
  categoria text not null,
  ubicacion text not null,
  modalidad text not null default 'PRESENCIAL'
    check (modalidad in ('PRESENCIAL', 'HIBRIDA', 'REMOTA')),
  fecha_publicacion date not null default current_date,
  cupos integer not null default 1 check (cupos >= 0),
  descripcion text,
  funciones text,
  requisitos text,
  beneficios text,
  sueldo text,
  publicada boolean not null default false,
  responsable_id bigint references public.cuentas (id) on delete set null,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create index if not exists idx_ofertas_publicada
  on public.ofertas (publicada, fecha_publicacion desc);

create index if not exists idx_ofertas_categoria
  on public.ofertas (categoria);

create index if not exists idx_ofertas_responsable
  on public.ofertas (responsable_id);

-- 3. Postulantes -----------------------------------------------

create table if not exists public.postulantes (
  id bigint generated by default as identity primary key,
  nombre text not null,
  rut text not null unique,
  correo text,
  telefono text,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create index if not exists idx_postulantes_correo
  on public.postulantes (lower(correo));

-- 4. Postulaciones ---------------------------------------------

create table if not exists public.postulaciones (
  id bigint generated by default as identity primary key,
  oferta_id bigint not null references public.ofertas (id) on delete cascade,
  postulante_id bigint not null references public.postulantes (id) on delete cascade,
  solicitud_id bigint references public.solicitudes (id) on delete set null,
  cv_drive_file_id text,
  cv_nombre text,
  estado text not null default 'RECIBIDA'
    check (estado in ('RECIBIDA', 'EN_REVISION', 'RECHAZADA', 'CONTRATADA')),
  observaciones text,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  unique (oferta_id, postulante_id)
);

create unique index if not exists ux_postulaciones_solicitud
  on public.postulaciones (solicitud_id)
  where solicitud_id is not null;

create index if not exists idx_postulaciones_oferta
  on public.postulaciones (oferta_id, created_at desc);

create index if not exists idx_postulaciones_postulante
  on public.postulaciones (postulante_id, created_at desc);

create index if not exists idx_postulaciones_estado
  on public.postulaciones (estado);

-- 5. Permisos ---------------------------------------------------

revoke all on public.ofertas from anon, authenticated;
revoke all on public.postulantes from anon, authenticated;
revoke all on public.postulaciones from anon, authenticated;

notify pgrst, 'reload schema';

commit;
