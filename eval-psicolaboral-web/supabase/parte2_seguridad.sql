-- ============================================================
-- Parte 2 - Seguridad y sesiones (AquaChile)
-- ------------------------------------------------------------
-- Ejecutar DESPUÉS de schema.sql y seed.sql.
-- Es idempotente: se puede volver a ejecutar sin duplicar datos.
--
-- Qué hace:
--   1. Agrega password_hash a cuentas y lo rellena con BCrypt.
--   2. Crea la tabla refresh_tokens (sesiones renovables).
--   3. Protege refresh_tokens para que la anon key no pueda leerla.
--
-- NO elimina la columna password ni las políticas anon de cuentas/
-- solicitudes: eso se hará cuando el frontend ya consuma el backend.
-- ============================================================

create extension if not exists pgcrypto;

-- 1. Hash de contraseñas -------------------------------------
alter table public.cuentas
  add column if not exists password_hash text;

-- Rellena solo las cuentas que todavía no tienen hash.
-- crypt(..., gen_salt('bf', 10)) genera BCrypt compatible con Spring Security.
update public.cuentas
set password_hash = crypt(password, gen_salt('bf', 10))
where password_hash is null
  and password is not null;

-- La columna queda nullable a propósito: el frontend antiguo puede crear
-- cuentas sin password_hash. El backend las migra en el primer login.

comment on column public.cuentas.password_hash is
  'Hash BCrypt de la contraseña. El backend nunca expone este valor.';

-- 2. Refresh tokens ------------------------------------------
create table if not exists public.refresh_tokens (
  id bigint generated by default as identity primary key,
  cuenta_id bigint not null references public.cuentas (id) on delete cascade,
  token_hash text not null unique,
  expira_en timestamptz not null,
  revocado boolean not null default false,
  creado_en timestamptz not null default now()
);

create index if not exists idx_refresh_tokens_cuenta
  on public.refresh_tokens (cuenta_id);

create index if not exists idx_refresh_tokens_expira
  on public.refresh_tokens (expira_en);

-- 3. RLS de refresh_tokens -----------------------------------
-- El backend se conecta con el rol postgres (dueño de las tablas), por lo
-- que puede operar aunque RLS esté activo. anon/authenticated no deben ver
-- esta tabla.
alter table public.refresh_tokens enable row level security;

do $$
begin
  if exists (select 1 from pg_roles where rolname = 'anon') then
    execute 'revoke all on public.refresh_tokens from anon';
  end if;
  if exists (select 1 from pg_roles where rolname = 'authenticated') then
    execute 'revoke all on public.refresh_tokens from authenticated';
  end if;
end
$$;

-- 4. Verificación rápida -------------------------------------
-- Debe mostrar todas las cuentas con un hash que empieza en $2a$/$2b$.
select id, correo, left(password_hash, 7) as hash_prefijo
from public.cuentas
order by id;

