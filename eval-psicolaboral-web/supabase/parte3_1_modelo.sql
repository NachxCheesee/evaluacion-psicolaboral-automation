create extension if not exists pgcrypto;

create sequence if not exists public.solicitudes_codigo_seq;

-- 1. Catalogos ------------------------------------------------

create table if not exists public.roles (
  id bigint generated by default as identity primary key,
  codigo text not null unique,
  nombre text not null,
  descripcion text,
  es_sistema boolean not null default true,
  activo boolean not null default true,
  created_at timestamptz not null default now()
);

create table if not exists public.permisos (
  id bigint generated by default as identity primary key,
  codigo text not null unique,
  nombre text not null,
  descripcion text,
  modulo text not null,
  activo boolean not null default true,
  created_at timestamptz not null default now()
);

create table if not exists public.rol_permisos (
  rol_id bigint not null references public.roles (id) on delete cascade,
  permiso_id bigint not null references public.permisos (id) on delete cascade,
  primary key (rol_id, permiso_id)
);

create table if not exists public.estados_solicitud (
  id bigint generated by default as identity primary key,
  codigo text not null unique,
  nombre text not null,
  descripcion text,
  orden smallint not null default 0,
  es_final boolean not null default false,
  color text,
  activo boolean not null default true,
  created_at timestamptz not null default now()
);

create table if not exists public.estados_usuario (
  id bigint generated by default as identity primary key,
  codigo text not null unique,
  nombre text not null,
  descripcion text,
  activo boolean not null default true,
  created_at timestamptz not null default now()
);

create table if not exists public.estados_candidato (
  id bigint generated by default as identity primary key,
  codigo text not null unique,
  nombre text not null,
  descripcion text,
  es_final boolean not null default false,
  activo boolean not null default true,
  created_at timestamptz not null default now()
);

create table if not exists public.familias_cargo (
  id bigint generated by default as identity primary key,
  nombre text not null unique,
  descripcion text,
  activo boolean not null default true,
  created_at timestamptz not null default now()
);

create table if not exists public.cargos (
  id bigint generated by default as identity primary key,
  familia_cargo_id bigint not null references public.familias_cargo (id) on delete restrict,
  nombre text not null,
  descripcion text,
  activo boolean not null default true,
  created_at timestamptz not null default now(),
  unique (familia_cargo_id, nombre)
);

create table if not exists public.resultados_evaluacion (
  id bigint generated by default as identity primary key,
  codigo text not null unique,
  nombre text not null,
  descripcion text,
  es_final boolean not null default false,
  activo boolean not null default true,
  created_at timestamptz not null default now()
);

create table if not exists public.origenes_solicitud (
  id bigint generated by default as identity primary key,
  codigo text not null unique,
  nombre text not null,
  activo boolean not null default true,
  created_at timestamptz not null default now()
);

create table if not exists public.tipos_documento (
  id bigint generated by default as identity primary key,
  codigo text not null unique,
  nombre text not null,
  obligatorio boolean not null default false,
  activo boolean not null default true,
  created_at timestamptz not null default now()
);

create table if not exists public.tipos_entrevista (
  id bigint generated by default as identity primary key,
  codigo text not null unique,
  nombre text not null,
  activo boolean not null default true,
  created_at timestamptz not null default now()
);

-- 2. Cuentas (usuarios) ---------------------------------------

alter table public.cuentas
  add column if not exists rol_id bigint references public.roles (id) on delete set null,
  add column if not exists estado_id bigint references public.estados_usuario (id) on delete set null,
  add column if not exists ultimo_acceso timestamptz,
  add column if not exists created_at timestamptz not null default now(),
  add column if not exists updated_at timestamptz not null default now();

alter table public.cuentas alter column password drop not null;

create index if not exists idx_cuentas_rol on public.cuentas (rol_id);
create index if not exists idx_cuentas_estado on public.cuentas (estado_id);

-- 3. Candidatos -----------------------------------------------

create table if not exists public.candidatos (
  id bigint generated by default as identity primary key,
  rut text not null,
  rut_normalizado text generated always as (
    upper(regexp_replace(rut, '[^0-9kK]', '', 'g'))
  ) stored,
  nombre_completo text not null,
  nombres text,
  apellidos text,
  email text,
  telefono text,
  direccion text,
  comuna text,
  region text,
  fecha_nacimiento date,
  genero text,
  es_interno boolean not null default false,
  id_empleado text,
  estado_id bigint references public.estados_candidato (id) on delete set null,
  creado_por bigint references public.cuentas (id) on delete set null,
  origen_registro text,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  constraint candidatos_rut_normalizado_key unique (rut_normalizado)
);

create index if not exists idx_candidatos_email on public.candidatos (lower(email));
create index if not exists idx_candidatos_estado on public.candidatos (estado_id);
create index if not exists idx_candidatos_nombre on public.candidatos (lower(nombre_completo));

-- 4. Solicitudes ----------------------------------------------

alter table public.solicitudes
  add column if not exists codigo text,
  add column if not exists candidato_id bigint references public.candidatos (id) on delete set null,
  add column if not exists cargo_id bigint references public.cargos (id) on delete set null,
  add column if not exists familia_cargo_id bigint references public.familias_cargo (id) on delete set null,
  add column if not exists estado_id bigint references public.estados_solicitud (id) on delete set null,
  add column if not exists origen_id bigint references public.origenes_solicitud (id) on delete set null,
  add column if not exists solicitado_por_id bigint references public.cuentas (id) on delete set null,
  add column if not exists evaluador_asignado_id bigint references public.cuentas (id) on delete set null,
  add column if not exists prioridad text,
  add column if not exists fecha_cierre timestamptz,
  add column if not exists created_at timestamptz not null default now(),
  add column if not exists updated_at timestamptz not null default now();

do $$
begin
  if not exists (
    select 1 from pg_constraint where conname = 'solicitudes_prioridad_check'
  ) then
    alter table public.solicitudes
      add constraint solicitudes_prioridad_check
      check (prioridad is null or prioridad in ('BAJA', 'MEDIA', 'ALTA'));
  end if;
end
$$;

create unique index if not exists ux_solicitudes_codigo
  on public.solicitudes (codigo)
  where codigo is not null;

create index if not exists idx_solicitudes_candidato_id on public.solicitudes (candidato_id);
create index if not exists idx_solicitudes_cargo_id on public.solicitudes (cargo_id);
create index if not exists idx_solicitudes_familia_id on public.solicitudes (familia_cargo_id);
create index if not exists idx_solicitudes_estado_id on public.solicitudes (estado_id);
create index if not exists idx_solicitudes_origen_id on public.solicitudes (origen_id);
create index if not exists idx_solicitudes_solicitante on public.solicitudes (solicitado_por_id);
create index if not exists idx_solicitudes_evaluador on public.solicitudes (evaluador_asignado_id);
create index if not exists idx_solicitudes_created_at on public.solicitudes (created_at desc);

-- 5. Evaluaciones ---------------------------------------------

create table if not exists public.evaluaciones (
  id bigint generated by default as identity primary key,
  solicitud_id bigint not null references public.solicitudes (id) on delete cascade,
  evaluador_id bigint references public.cuentas (id) on delete set null,
  fecha_entrevista date,
  tipo_entrevista_id bigint references public.tipos_entrevista (id) on delete set null,
  resultado_id bigint references public.resultados_evaluacion (id) on delete set null,
  observaciones text,
  fecha_evaluacion timestamptz,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  constraint evaluaciones_solicitud_id_key unique (solicitud_id)
);

create index if not exists idx_evaluaciones_evaluador on public.evaluaciones (evaluador_id);
create index if not exists idx_evaluaciones_resultado on public.evaluaciones (resultado_id);
create index if not exists idx_evaluaciones_fecha on public.evaluaciones (fecha_entrevista desc);

-- 6. Documentos -----------------------------------------------

create table if not exists public.documentos (
  id bigint generated by default as identity primary key,
  solicitud_id bigint not null references public.solicitudes (id) on delete cascade,
  candidato_id bigint references public.candidatos (id) on delete set null,
  tipo_documento_id bigint not null references public.tipos_documento (id) on delete restrict,
  nombre_archivo text not null,
  storage_path text,
  mime_type text,
  tamano_bytes bigint,
  subido_por bigint references public.cuentas (id) on delete set null,
  created_at timestamptz not null default now(),
  unique (solicitud_id, tipo_documento_id)
);

create index if not exists idx_documentos_solicitud on public.documentos (solicitud_id);
create index if not exists idx_documentos_candidato on public.documentos (candidato_id);
create index if not exists idx_documentos_tipo on public.documentos (tipo_documento_id);

-- 7. Historial ------------------------------------------------

create table if not exists public.historial_cambios (
  id bigint generated by default as identity primary key,
  tabla text not null,
  registro_id bigint not null,
  accion text not null check (accion in ('INSERT', 'UPDATE', 'DELETE')),
  datos_anteriores jsonb,
  datos_nuevos jsonb,
  usuario_id bigint references public.cuentas (id) on delete set null,
  ip inet,
  user_agent text,
  motivo text,
  created_at timestamptz not null default now()
);

create index if not exists idx_historial_registro
  on public.historial_cambios (tabla, registro_id, created_at desc);
create index if not exists idx_historial_usuario
  on public.historial_cambios (usuario_id, created_at desc);

create table if not exists public.historial_estados_solicitud (
  id bigint generated by default as identity primary key,
  solicitud_id bigint not null references public.solicitudes (id) on delete cascade,
  estado_anterior_id bigint references public.estados_solicitud (id) on delete set null,
  estado_nuevo_id bigint references public.estados_solicitud (id) on delete set null,
  usuario_id bigint references public.cuentas (id) on delete set null,
  comentario text,
  created_at timestamptz not null default now()
);

create index if not exists idx_historial_estados_solicitud
  on public.historial_estados_solicitud (solicitud_id, created_at desc);

-- 8. Tablas opcionales sugeridas -------------------------------

create table if not exists public.notificaciones (
  id bigint generated by default as identity primary key,
  usuario_id bigint references public.cuentas (id) on delete cascade,
  solicitud_id bigint references public.solicitudes (id) on delete cascade,
  tipo text,
  titulo text not null,
  mensaje text,
  leida boolean not null default false,
  created_at timestamptz not null default now()
);

create index if not exists idx_notificaciones_usuario
  on public.notificaciones (usuario_id, leida, created_at desc);

create table if not exists public.parametros_sistema (
  clave text primary key,
  valor jsonb,
  descripcion text,
  updated_at timestamptz not null default now()
);

create table if not exists public.historial_accesos (
  id bigint generated by default as identity primary key,
  usuario_id bigint references public.cuentas (id) on delete set null,
  correo_intentado text,
  exitoso boolean not null default false,
  ip inet,
  user_agent text,
  created_at timestamptz not null default now()
);

create index if not exists idx_historial_accesos_usuario
  on public.historial_accesos (usuario_id, created_at desc);

